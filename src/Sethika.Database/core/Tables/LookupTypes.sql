CREATE TABLE core.LookupTypes (
    Id       SMALLINT      IDENTITY(1,1) PRIMARY KEY,
    Code     VARCHAR(50)   NOT NULL UNIQUE,  -- OCCASION, NEED_CATEGORY, UNIT, PAYMENT_METHOD, RELIGION, RELATIONSHIP, REJECT_REASON, REPORT_REASON
    Name     NVARCHAR(100) NOT NULL,
    IsSystem BIT           NOT NULL DEFAULT 1
);
GO
